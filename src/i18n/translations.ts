// Fast case-insensitive helper mapping
const lowerCasePhraseCache: Partial<Record<LanguageCode, Map<string, string>>> = {};

function getLowerCaseMap(lang: LanguageCode): Map<string, string> {
  if (lowerCasePhraseCache[lang]) {
    return lowerCasePhraseCache[lang]!;
  }
  const map = new Map<string, string>();
  // populate from translations
  if (translations[lang]) {
    for (const [k, v] of Object.entries(translations[lang])) {
      map.set(k.toLowerCase(), v);
    }
  }
  // populate from phraseTranslations
  if (phraseTranslations[lang]) {
    for (const [k, v] of Object.entries(phraseTranslations[lang])) {
      map.set(k.toLowerCase(), v);
    }
  }
  lowerCasePhraseCache[lang] = map;
  return map;
}

/**
 * Universal translate function that translates any key, phrase, or sentence to the target language.
 */
export function translateText(rawText: string, lang: LanguageCode): string {
  if (!rawText || typeof rawText !== 'string' || lang === 'en') {
    return rawText;
  }

  const trimmed = rawText.trim();
  if (!trimmed) {
    return rawText;
  }

  const leadingWhitespace = rawText.match(/^\s*/)?.[0] || '';
  const trailingWhitespace = rawText.match(/\s*$/)?.[0] || '';

  // 1. Direct key in translations
  const langDict = translations[lang];
  if (langDict && langDict[trimmed]) {
    return leadingWhitespace + langDict[trimmed] + trailingWhitespace;
  }

  // 2. Direct phrase in phraseTranslations
  const langPhrases = phraseTranslations[lang];
  if (langPhrases && langPhrases[trimmed]) {
    return leadingWhitespace + langPhrases[trimmed] + trailingWhitespace;
  }

  // 3. Case-insensitive lookup
  const lowerMap = getLowerCaseMap(lang);
  const match = lowerMap.get(trimmed.toLowerCase());
  if (match) {
    return leadingWhitespace + match + trailingWhitespace;
  }

  // 4. Fallback for strings containing numbers or simple prefixes, e.g. "27% Soil Moisture"
  const percentageSoilMoistureMatch = trimmed.match(/^(\d+%\s*)(Soil Moisture)$/i);
  if (percentageSoilMoistureMatch) {
    const translatedSuffix = translateText(percentageSoilMoistureMatch[2], lang);
    return leadingWhitespace + percentageSoilMoistureMatch[1] + translatedSuffix + trailingWhitespace;
  }

  // "Target: >35%"
  const targetMatch = trimmed.match(/^(Target:\s*)(.*)$/i);
  if (targetMatch) {
    const targetWord = lang === 'hi' ? 'लक्ष्य: ' : lang === 'te' ? 'లక్ష్యం: ' : lang === 'ta' ? 'இலக்கு: ' : lang === 'es' ? 'Objetivo: ' : 'Target: ';
    return leadingWhitespace + targetWord + targetMatch[2] + trailingWhitespace;
  }

  return rawText;
}
